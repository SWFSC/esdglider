def update_glider_configs(config_directory: Path, updates: dict):
    for file_path in config_directory.glob("*.yml"):
        with open(file_path, "r", encoding="utf-8") as f:
            print(f"Processing file: {file_path.name}")
            data = yaml.safe_load(f)

        file_updated = False

        for section_name, var_updates in updates.items():
            if section_name in data and isinstance(data[section_name], dict):
                for var_name, bounds in var_updates.items():
                    if var_name in data[section_name]:
                        data[section_name][var_name].update(bounds)
                        file_updated = True

        if file_updated:
            with open(file_path, "w", encoding="utf-8") as f:
                # sort_keys=False maintains key ordering
                # default_flow_style=False ensures YAML block style instead of JSON style
                yaml.dump(data, f, sort_keys=False, default_flow_style=False)
            print(f"Successfully updated: {file_path.name}")

